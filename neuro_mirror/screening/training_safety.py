"""Прерывание задания и красные флаги в курсе тренировок.

«Методика подбора и оценки тренировочного курса» v2:

* 6.3, «Прерывание задания»: причина записывается; при утомлении или плохом
  самочувствии первым предлагается завершить занятие с сохранением
  прогресса; если пользователь хочет продолжить — облегчённая альтернатива
  (та же форма уровнем ниже или другая форма того же домена). Облегчённый
  уровень временный и в уровень формы не записывается.
* 9, «Красные флаги»: внезапное ухудшение речи или памяти, спутанность,
  очаговые симптомы — тренировка прекращается, пользователю рекомендуется
  обратиться к врачу, специалист получает уведомление. Модуль сам таких
  изменений не распознаёт; источники сигнала — вопрос перед занятием и
  сообщение пользователя (здесь — причина прерывания «новые симптомы»).

Формулировку вопроса о новых симптомах методика поручает методистам с
неврологом (вопрос 2). Текст ниже — черновик команды, помечен как таковой
и меняется здесь.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Reason:
    code: str
    label: str
    # Утомление и самочувствие: первым предлагается завершить занятие
    finish_first: bool = False
    # Сообщение о новых симптомах: красный флаг
    red_flag: bool = False

    def to_dict(self) -> dict[str, object]:
        return {
            "code": self.code,
            "label": self.label,
            "finish_first": self.finish_first,
            "red_flag": self.red_flag,
        }


REASONS: tuple[Reason, ...] = (
    Reason("fatigue", "Устал(а)", finish_first=True),
    Reason("wellbeing", "Плохое самочувствие", finish_first=True),
    Reason("too_hard", "Задание слишком трудное"),
    Reason("symptoms", "Появились новые или необычные симптомы", red_flag=True),
    Reason("other", "Другая причина"),
)
BY_CODE = {reason.code: reason for reason in REASONS}

# Окончание занятия без прерывания задания: все задания выполнены
REASON_ALL_DONE = "все задания выполнены"


def reason_for(code: str) -> Reason | None:
    return BY_CODE.get(str(code or "").strip())


# Вопрос перед занятием (9, «Красные флаги»; вопрос 2 методики)
RED_FLAG_QUESTION = {
    "text": (
        "За последние дни вы замечали внезапное ухудшение памяти или речи, "
        "спутанность или другие новые необычные симптомы?"
    ),
    "options": [{"value": False, "label": "Нет"}, {"value": True, "label": "Да"}],
    "status": "draft",
    "note": "Черновик команды: формулировку утверждают методисты с неврологом (методика, вопрос 2).",
}

RED_FLAG_USER_TEXT = (
    "Тренировки приостановлены. Обратитесь, пожалуйста, к врачу: о таких "
    "изменениях важно рассказать специалисту. Продолжить курс можно после "
    "того, как специалист снимет приостановку."
)


def interruption_reasons() -> list[dict[str, object]]:
    return [reason.to_dict() for reason in REASONS]
